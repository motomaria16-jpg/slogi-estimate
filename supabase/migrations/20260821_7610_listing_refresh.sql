-- Atomically claim a new daily source slot or reclaim one that has remained
-- running past the caller-provided conservative stale threshold. Updating
-- started_at inside the same statement prevents two retries from reclaiming
-- the same stale row.
create or replace function public.slogi_claim_listing_scan_run(
  p_source text,
  p_phase text,
  p_run_slot timestamptz,
  p_started_at timestamptz,
  p_stale_before timestamptz
)
returns table (run_id bigint, claimed boolean, recovered boolean)
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_run_id bigint;
begin
  if p_source is distinct from 'cian' then
    raise exception using errcode = '22023', message = 'invalid_listing_source';
  end if;
  if p_phase is null or p_phase <> all (array['discovery'::text, 'hydration'::text]) then
    raise exception using errcode = '22023', message = 'invalid_listing_phase';
  end if;

  insert into public.slogi_listing_scan_runs (source, phase, run_slot, started_at, status)
  values (p_source, p_phase, p_run_slot, p_started_at, 'running')
  on conflict (source, phase, run_slot) do nothing
  returning id into v_run_id;

  if v_run_id is not null then
    return query select v_run_id, true, false;
    return;
  end if;

  update public.slogi_listing_scan_runs
  set
    started_at = p_started_at,
    finished_at = null,
    status = 'running',
    discovered = 0,
    queued_new = 0,
    queued_existing = 0,
    hot = 0,
    backfill = 0,
    claimed = 0,
    attempted = 0,
    parsed = 0,
    partial = 0,
    blocked = 0,
    failed = 0,
    inserted = 0,
    updated = 0,
    skipped_old = 0,
    skipped_unknown_date = 0,
    strategy = null,
    error_code = 'stale_run_recovered',
    diagnostic = jsonb_build_object(
      'recovery', 'stale_running_reclaimed',
      'recovered_at', p_started_at
    )
  where source = p_source
    and phase = p_phase
    and run_slot = p_run_slot
    and status = 'running'
    and started_at <= p_stale_before
  returning id into v_run_id;

  if v_run_id is not null then
    return query select v_run_id, true, true;
    return;
  end if;

  return query select null::bigint, false, false;
end;
$$;

