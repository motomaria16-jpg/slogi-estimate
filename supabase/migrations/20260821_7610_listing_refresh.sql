-- Discovery materializes canonical URLs only. It never treats discovered_at
-- as publication freshness and it never unlocks an in-flight item.
create or replace function public.slogi_enqueue_listing_fetches(
  p_source text,
  p_priority text,
  p_items jsonb,
  p_discovered_at timestamptz
)
returns table (listing_url text, queue_status text, queued_new boolean)
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_item jsonb;
  v_url text;
  v_external_id text;
  v_status text;
  v_new boolean;
begin
  if p_source is distinct from 'cian' then
    raise exception using errcode = '22023', message = 'invalid_listing_source';
  end if;
  if p_priority is null or p_priority <> all (array['hot'::text, 'backfill'::text]) then
    raise exception using errcode = '22023', message = 'invalid_listing_priority';
  end if;
  if p_discovered_at is null or pg_catalog.jsonb_typeof(p_items) <> 'array' or pg_catalog.jsonb_array_length(p_items) > 500 then
    raise exception using errcode = '22023', message = 'invalid_listing_queue_batch';
  end if;

  for v_item in select value from pg_catalog.jsonb_array_elements(p_items)
  loop
    v_url := pg_catalog.btrim(v_item ->> 'listingUrl');
    v_external_id := nullif(pg_catalog.btrim(v_item ->> 'externalId'), '');
    if v_url is null or v_url = '' or pg_catalog.length(v_url) > 2048 then
      raise exception using errcode = '22023', message = 'invalid_listing_url';
    end if;

    insert into public.slogi_listing_fetch_queue as q (
      source, listing_url, external_id, priority, status,
      discovered_at, last_discovered_at, next_attempt_at,
      created_at, updated_at
    ) values (
      p_source, v_url, v_external_id, p_priority, 'pending',
      p_discovered_at, p_discovered_at, p_discovered_at,
      p_discovered_at, p_discovered_at
    )
    on conflict on constraint slogi_listing_fetch_queue_source_url_key do update
    set
      external_id = coalesce(excluded.external_id, q.external_id),
      priority = case when excluded.priority = 'hot' then 'hot' else q.priority end,
      last_discovered_at = excluded.last_discovered_at,
      status = case
        when q.status = 'processing' then q.status
        when q.status in ('failed', 'blocked') and q.next_attempt_at > excluded.last_discovered_at then q.status
        when excluded.priority = 'hot'
          and coalesce(q.last_attempt_at, q.completed_at, q.discovered_at) <= excluded.last_discovered_at - interval '1 hour'
          then 'pending'
        when excluded.priority = 'backfill'
          and coalesce(q.last_attempt_at, q.completed_at, q.discovered_at) <= excluded.last_discovered_at - interval '24 hours'
          then 'pending'
        else q.status
      end,
      next_attempt_at = case
        when q.status = 'processing' then q.next_attempt_at
        when q.status in ('failed', 'blocked') and q.next_attempt_at > excluded.last_discovered_at then q.next_attempt_at
        when excluded.priority = 'hot'
          and coalesce(q.last_attempt_at, q.completed_at, q.discovered_at) <= excluded.last_discovered_at - interval '1 hour'
          then excluded.last_discovered_at
        when excluded.priority = 'backfill'
          and coalesce(q.last_attempt_at, q.completed_at, q.discovered_at) <= excluded.last_discovered_at - interval '24 hours'
          then excluded.last_discovered_at
        else q.next_attempt_at
      end,
      locked_at = case when q.status = 'processing' then q.locked_at else null end,
      locked_by = case when q.status = 'processing' then q.locked_by else null end,
      completed_at = case
        when q.status = 'processing' then q.completed_at
        when (excluded.priority = 'hot' and coalesce(q.last_attempt_at, q.completed_at, q.discovered_at) <= excluded.last_discovered_at - interval '1 hour')
          or (excluded.priority = 'backfill' and coalesce(q.last_attempt_at, q.completed_at, q.discovered_at) <= excluded.last_discovered_at - interval '24 hours')
          then null
        else q.completed_at
      end,
      updated_at = excluded.updated_at
    returning q.status, (xmax = 0) into v_status, v_new;

    return query select v_url, v_status, v_new;
  end loop;
end;
$$;

