create or replace function public.slogi_finish_listing_fetch_queue(
  p_id bigint,
  p_worker_id uuid,
  p_status text,
  p_finished_at timestamptz,
  p_next_attempt_at timestamptz,
  p_error_code text,
  p_diagnostic jsonb
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_updated bigint;
begin
  if p_status is null or p_status <> all (array[
    'retry'::text, 'completed'::text, 'discarded_old'::text,
    'discarded_unknown_date'::text, 'blocked'::text, 'failed'::text
  ]) then
    raise exception using errcode = '22023', message = 'invalid_listing_queue_status';
  end if;
  if p_worker_id is null or p_finished_at is null then
    raise exception using errcode = '22023', message = 'invalid_listing_finish';
  end if;
  if p_status = 'retry' and (p_next_attempt_at is null or p_next_attempt_at <= p_finished_at) then
    raise exception using errcode = '22023', message = 'invalid_listing_retry_time';
  end if;

  update public.slogi_listing_fetch_queue
  set
    status = p_status,
    next_attempt_at = coalesce(p_next_attempt_at, p_finished_at),
    locked_at = null,
    locked_by = null,
    completed_at = case when p_status = 'completed' then p_finished_at else completed_at end,
    last_error_code = nullif(pg_catalog.btrim(p_error_code), ''),
    diagnostic = coalesce(p_diagnostic, '{}'::jsonb),
    updated_at = p_finished_at
  where id = p_id and status = 'processing' and locked_by = p_worker_id;

  get diagnostics v_updated = row_count;
  return v_updated = 1;
end;
$$;

