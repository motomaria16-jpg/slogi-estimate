-- ==========================================================
-- 7. STORAGE BASELINE
-- ==========================================================
-- Live observations:
--   bucket = slogi-files
--   file size limit = 50 MiB
--   allowed MIME types = Any
--   policies observed = 4
--
-- The policy definitions below are reproduced from recovered
-- SUPABASE_SETUP.sql and are consistent with that observed topology.

insert into storage.buckets (
  id,
  name,
  public,
  file_size_limit,
  allowed_mime_types
)
values (
  'slogi-files',
  'slogi-files',
  false,
  52428800,
  null
)
on conflict (id) do update
set
  name = excluded.name,
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "SLOGI files select own" on storage.objects;
drop policy if exists "SLOGI files insert own" on storage.objects;
drop policy if exists "SLOGI files update own" on storage.objects;
drop policy if exists "SLOGI files delete own" on storage.objects;

create policy "SLOGI files select own"
on storage.objects
for select
to authenticated
using (
  bucket_id = 'slogi-files'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
);

create policy "SLOGI files insert own"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'slogi-files'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
);

create policy "SLOGI files update own"
on storage.objects
for update
to authenticated
using (
  bucket_id = 'slogi-files'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
)
with check (
  bucket_id = 'slogi-files'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
);

create policy "SLOGI files delete own"
on storage.objects
for delete
to authenticated
using (
  bucket_id = 'slogi-files'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
);

commit;

