create table public.slogi_user_state (
  user_id uuid not null,
  locations jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint slogi_user_state_pkey primary key (user_id),
  constraint slogi_user_state_user_id_fkey
    foreign key (user_id) references auth.users(id) on delete cascade
);

create table public.slogi_workspace_state (
  user_id uuid not null,
  workspace jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint slogi_workspace_state_pkey primary key (user_id),
  constraint slogi_workspace_state_user_id_fkey
    foreign key (user_id) references auth.users(id) on delete cascade
);

create table public.slogi_attachments (
  user_id uuid not null,
  location_id text not null,
  attachment_type text not null,
  file_name text not null default 'Файл'::text,
  mime_type text not null default 'application/octet-stream'::text,
  storage_path text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint slogi_attachments_pkey
    primary key (user_id, location_id, attachment_type),
  constraint slogi_attachments_user_id_fkey
    foreign key (user_id) references auth.users(id) on delete cascade
);

-- ==========================================================
-- 2. MARKET ANALYSIS TABLES
-- ==========================================================

create table public.slogi_market_listings (
  id bigint generated by default as identity not null,
  source text not null,
  listing_url text not null,
  address text,
  cluster_name text,
  area numeric,
  floor numeric,
  rent_monthly numeric,
  previous_rent_monthly numeric,
  latitude double precision,
  longitude double precision,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  last_checked_at timestamptz not null default now(),
  market_status text not null default 'new'::text,
  price_changed boolean not null default false,
  missed_scans integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint slogi_market_listings_pkey
    primary key (id),

  constraint slogi_market_listings_source_check
    check (source = any (array['cian'::text, 'avito'::text])),

  constraint slogi_market_listings_market_status_check
    check (market_status = any (
      array['new'::text, 'active'::text, 'removed'::text]
    )),

  constraint slogi_market_listings_source_listing_url_key
    unique (source, listing_url)
);

create table public.slogi_market_price_history (
  id bigint generated by default as identity not null,
  source text not null,
  listing_url text not null,
  rent_monthly numeric not null,
  recorded_at timestamptz not null default now(),

  constraint slogi_market_price_history_pkey
    primary key (id),

  constraint slogi_market_price_history_source_check
    check (source = any (array['cian'::text, 'avito'::text]))
);

